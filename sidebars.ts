import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';
import {TRACKS, type Track} from './src/data/tracks';

// Each track has its own sidebar, so a learner inside a track sees only that track. The `course`
// sidebar holds the pages that belong to no track: the welcome page, the glossary and what's next.

type SidebarItems = Extract<SidebarsConfig[string], unknown[]>;

function trackSidebar(track: Track): SidebarItems {
  const label = `${track.icon}\u2002${track.title}`;
  return [
    {
      type: 'category',
      label,
      collapsible: false,
      link: {type: 'generated-index', slug: `/${track.id}`, title: label, description: track.description},
      items: [{type: 'autogenerated', dirName: track.id}],
    },
    {type: 'html', value: '<hr class="sidebar-divider" />', defaultStyle: false},
    {type: 'link', label: '← All tracks', href: '/docs/intro'},
    {type: 'link', label: '📈\u2002My progress', href: '/progress'},
  ];
}

const sidebars: SidebarsConfig = {
  course: [
    'intro',
    ...TRACKS.map((t) => ({type: 'link' as const, label: `${t.icon}\u2002${t.title}`, href: `/docs/${t.id}`})),
    'glossary',
    'whats-next',
    {type: 'link', label: '📈\u2002My progress', href: '/progress'},
  ],
  ...Object.fromEntries(TRACKS.map((t) => [t.id, trackSidebar(t)])),
};

export default sidebars;
